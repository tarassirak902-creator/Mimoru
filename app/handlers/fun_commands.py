FUN_ACTIONS = frozenset(ACTIONS) | frozenset(RANDOM_ACTIONS)


def _name(user) -> str:
    if user.username:
        return f"@{user.username}"
    return user.full_name or str(user.id)


def _pick_text(action: str) -> str:
    if action in RANDOM_ACTIONS:
        return random.choice(RANDOM_ACTIONS[action])
    roll = random.randint(1, 100)
    cursor = 0
    for chance, text in RARE_EVENTS.get(action, []):
        cursor += chance
        if roll <= cursor:
            return text
    return ACTIONS[action]


@router.message(F.chat.type.in_(GROUP_TYPES), F.reply_to_message, F.text.casefold().in_(FUN_ACTIONS))
async def fun_reply_action(message: Message, session: AsyncSession) -> None:
    if message.from_user is None or message.reply_to_message.from_user is None:
        return
    actor = message.from_user
    target = message.reply_to_message.from_user
    action = " ".join((message.text or "").casefold().strip().split())
    if target.is_bot:
        return
    if actor.id == target.id:
        await message.reply("С самим собой это выглядит слишком подозрительно 😏")
        return

    key = (message.chat.id, actor.id)
    now = time.monotonic()
    previous = _action_cooldowns.get(key, 0.0)
    if now - previous < ACTION_COOLDOWN_SECONDS:
        await message.reply("⏳ Секунду, герой. Дайте чату хотя бы 3 секунды перед следующим игровым действием 😄")
        return
    _action_cooldowns[key] = now

    text = _pick_text(action).format(
        user1=_name(actor), user2=_name(target), chance=random.randint(0, 100),
        loot=random.randint(1, 999), sentence=random.randint(1, 60),
    )
    await message.reply(text)

    group = await session.scalar(select(Group).where(Group.telegram_chat_id == message.chat.id, Group.is_active.is_(True)))
    if group is not None:
        session.add(GameEvent(
            group_id=group.id, event_type="action", action=action,
            actor_telegram_id=actor.id, target_telegram_id=target.id,
            actor_name=_name(actor), target_name=_name(target), outcome="done",
        ))
        await session.commit()
